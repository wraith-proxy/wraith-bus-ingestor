{#
  The fitted ETA model. One ordinary-least-squares line per grain:

      remaining_secs = intercept_s + slope_s_per_km * remaining_km

  A least-squares line needs only six numbers per group, and
  int_eta_daily_stats keeps exactly those per finest cell per local date, so
  the whole "training" step is still a GROUP BY -- one that pools those daily
  rows rather than scanning every ping (see "Where the fit comes from" below).
  No Python, no scikit-learn, no model file to ship, no training/serving skew
  -- the fitted coefficients ARE the mart, and Flask does inference with one
  multiply and one add.

  ---------------------------------------------------------------------------
  The grain, and the fallback chain
  ---------------------------------------------------------------------------
  The finest grain is (operator, line, direction, day_type, hour_band): the 192
  inbound on a Tuesday morning is a genuinely different service from the 192
  inbound on a Sunday night -- different frequency, different traffic,
  different number of stops actually served. operator sits ABOVE all of that,
  because a shared line number is not even the same physical service: '88' is
  a Sheffield cross-city route AND an unrelated Wilmslow-Hale route, and until
  2026-09-12 nothing in this feed told them apart at all.

  But splitting five ways thins every cell, and plenty of combinations have too
  few observations to fit anything trustworthy. The API must never fail to find
  a model, so the same table is emitted at eleven widths, each strictly
  coarser, and Flask walks them in order until one hits:

      (operator, line, direction, day_type, hour_band)   this operator, the real thing
      (operator, line, direction, day_type, '*')         this operator, that day pattern
      (operator, line, direction, '*',      hour_band)   this operator, that time of day
      (operator, line, direction, '*',      '*')         this operator, the route
      (operator, line, '*',       '*',      '*')         this operator, the service number
      ('*',      line, direction, day_type, hour_band)   any operator, the real thing
      ('*',      line, direction, day_type, '*')         any operator, that day pattern
      ('*',      line, direction, '*',      hour_band)   any operator, that time of day
      ('*',      line, direction, '*',      '*')         any operator, the route, both times pooled
      ('*',      line, '*',       '*',      '*')         any operator, the service number
      ('*',      '*',  '*',       '*',      '*')         the network average, always present

  The operator-specific rungs only exist where operator is not null -- every
  ping before 2026-09-12 has no operator at all, so those rows can only ever
  feed the '*'-operator rungs (rungs 6-11, the original six-rung chain this
  table used to be in full). A live bus without an operator, or one whose
  operator has too little history to fit rungs 1-5, falls straight through to
  the same '*' chain that has always existed. Nothing that worked before this
  column existed stopped working.

  Rungs 2/3 (and 7/8) are siblings, not nested: given a thin cell, we would
  rather keep the day pattern and lose the hour, than the reverse -- a Sunday
  fitted from weekday data is worse than a Sunday fitted across the whole day.

  EVERY FALLBACK IS REFITTED at that width, never averaged from the finer rows.
  Averaging slopes would weight a 300-observation grain the same as a
  300,000-observation one, which is exactly backwards. Pooling the daily
  statistics is not averaging: it gives the line regr_slope() would fit over
  the underlying pings, to floating-point rounding.

  The eleven fits are generated by the Jinja loop below rather than written out
  eleven times. Each entry lists which columns are real at that grain;
  everything else becomes the literal '*'.

  ---------------------------------------------------------------------------
  Where the fit comes from
  ---------------------------------------------------------------------------
  Until ADR-0010 this ran regr_slope/regr_intercept/regr_r2/regr_count over
  int_pings_measured_to_journey_end, one row per training ping, which tied the
  model's memory to the raw ping window: eight days of training meant eight
  days of raw pings on the SSD. It now reads int_eta_daily_stats, which keeps,
  per (local date, finest cell), n_obs, the means avg_km and avg_secs, and the
  CENTRED sums sxx, sxy and syy, for history_days() after the pings behind them
  are gone (see that model's header).

  A rung pools every retained date and every finest cell inside it. For a rung
  group whose cells i each have n_i rows, means x_i (km) and y_i (secs), and
  centred sums sxx_i, sxy_i, syy_i:

      N   = sum(n_i)
      MX  = sum(n_i * x_i) / N              MY = sum(n_i * y_i) / N
      SXX = sum(sxx_i + n_i * (x_i - MX)^2)
      SXY = sum(sxy_i + n_i * (x_i - MX) * (y_i - MY))
      SYY = sum(syy_i + n_i * (y_i - MY)^2)

      slope = SXY / SXX    intercept = MY - slope * MX    r2 = SXY^2 / (SXX * SYY)

  This is Chan, Golub & LeVeque's pairwise combination, the standard way to
  merge partial variances: exact, and because every term is centred it does
  not lose precision the way sum(x^2) - N * MX^2 would. MX and MY belong to
  the whole rung group, so `cells` puts them on every cell with a window over
  the group before `pooled` takes the sums.

  A degenerate group comes out as the aggregates gave it (checked against
  DuckDB 1.5.5's own regr_* in memory): every x equal (SXX = 0) is a NaN slope
  with a NULL intercept and r2; every y equal (SYY = 0) is slope 0 and r2 1.
  `sane` drops both. The one departure is that r2 is capped at 1. regr_r2()
  itself lands a hair above 1 on perfectly collinear data, pooling can do the
  same, and bus-marts' eta_r2_in_range gate would refuse to publish on it.

  dbt/tests/assert_eta_stats_match_raw_fit.sql guards this in two parts: it
  checks int_eta_daily_stats against regr_* over the raw pings on the recent
  dates, and it checks this model's network and per-line rows (rungs 11 and
  10) against its own independent pooling of int_eta_daily_stats.

  ---------------------------------------------------------------------------
  Why a grain gets rejected
  ---------------------------------------------------------------------------
  A fit is kept only if it is both well-supported and physically possible:
    - at least 200 observations
    - positive slope (a negative slope says "the further away, the sooner you
      arrive", which is a fit to noise)
    - implied mean speed between 3 and 90 km/h
  A grain that fails is simply not emitted and the lookup falls through to the
  next coarser rung. No model is better than a wrong model.
#}

{%- set key_columns = ['operator', 'line', 'direction', 'day_type', 'hour_band'] -%}
{%- set grains = [
      ['operator', 'line', 'direction', 'day_type', 'hour_band'],
      ['operator', 'line', 'direction', 'day_type'],
      ['operator', 'line', 'direction', 'hour_band'],
      ['operator', 'line', 'direction'],
      ['operator', 'line'],
      ['line', 'direction', 'day_type', 'hour_band'],
      ['line', 'direction', 'day_type'],
      ['line', 'direction', 'hour_band'],
      ['line', 'direction'],
      ['line'],
      []
   ] -%}

with daily_stats as (

    select * from {{ ref('int_eta_daily_stats') }}

),

cells as (

{% for grain in grains %}
    -- Rung {{ loop.index }}: {% if grain %}grouped by {{ grain | join(', ') }}{% else %}the whole network in one fit{% endif %}

    select
        {% for col in key_columns -%}
        {% if col in grain %}{{ col }}{% else %}'*'{% endif %} as {{ col }},
        {% endfor -%}
        {{ loop.index }} as grain_rank,
        n_obs,
        avg_km,
        avg_secs,
        sxx,
        sxy,
        syy,
        -- MX and MY of the whole rung group, carried on each of its cells.
        -- (Spelled out per branch: DuckDB will not take the same WINDOW name
        -- twice in one UNION.)
        {% set rung = 'partition by ' ~ grain | join(', ') if grain else '' -%}
        sum(n_obs * avg_km)   over ({{ rung }}) / sum(n_obs) over ({{ rung }}) as rung_avg_km,
        sum(n_obs * avg_secs) over ({{ rung }}) / sum(n_obs) over ({{ rung }}) as rung_avg_secs
    from daily_stats
    -- A NULL-keyed "operator-specific" or "direction-specific" grain would
    -- never be looked up: a live bus with no operator skips straight to the
    -- '*'-operator rungs, and one with no DirectionRef (31.9% of journeys
    -- since the heuristic that used to fill this gap was retired, ROADMAP.md
    -- 1.2.0) skips straight to the '*'-direction rungs. Exclude both rather
    -- than waste a rung on a fit nothing will ever match -- and rather than
    -- publish a NULL in `direction`, which is `required`/`primaryKey` in
    -- bus-marts.odcs.yaml precisely because every OTHER rung's `direction`
    -- is either a real value or the literal '*', never NULL.
    {% set null_guards = [] %}
    {% if 'operator' in grain %}{% do null_guards.append('operator is not null') %}{% endif %}
    {% if 'direction' in grain %}{% do null_guards.append('direction is not null') %}{% endif %}
    {% if null_guards %}where {{ null_guards | join(' and ') }}{% endif %}

{% if not loop.last %}    union all
{% endif %}
{%- endfor %}

),

pooled as (

    -- One row per rung group: the six statistics of the union of its cells.
    select
        operator,
        line,
        direction,
        day_type,
        hour_band,
        grain_rank,
        sum(n_obs)                                                                 as rung_n_obs,
        any_value(rung_avg_km)                                                     as rung_avg_km,
        any_value(rung_avg_secs)                                                   as rung_avg_secs,
        sum(sxx + n_obs * (avg_km - rung_avg_km) * (avg_km - rung_avg_km))         as rung_sxx,
        sum(sxy + n_obs * (avg_km - rung_avg_km) * (avg_secs - rung_avg_secs))     as rung_sxy,
        sum(syy + n_obs * (avg_secs - rung_avg_secs) * (avg_secs - rung_avg_secs)) as rung_syy
    from cells
    group by operator, line, direction, day_type, hour_band, grain_rank

),

stacked as (

    -- The pooled line, answering the degenerate groups the way regr_* does
    -- (see "Where the fit comes from"). The slope is left a plain division
    -- on purpose: SXX = 0 gives 0 / 0 = NaN, which is what regr_slope()
    -- returns, while intercept and r2 come out NULL there, as regr_intercept()
    -- and regr_r2() do. least() is only there for rounding.
    select
        operator,
        line,
        direction,
        day_type,
        hour_band,
        grain_rank,
        rung_sxy / rung_sxx                                          as slope_s_per_km,
        rung_avg_secs - rung_sxy / nullif(rung_sxx, 0) * rung_avg_km as intercept_s,
        case
            when rung_sxx = 0 then null
            when rung_syy = 0 then 1
            else least(1.0, rung_sxy * rung_sxy / (rung_sxx * rung_syy))
        end                                                          as r2,
        rung_n_obs                                                   as n_obs
    from pooled

),

sane as (

    select *
    from stacked
    where n_obs >= 200                                  -- too thin to trust
      and slope_s_per_km is not null
      and slope_s_per_km > 0                            -- negative pace is a fit to noise
      and 3600.0 / slope_s_per_km between 3 and 90      -- 3 km/h is a parked bus, 90 km/h is not a bus

),

deduped as (

    -- Defensive. The eleven grains are distinct by construction as long as no
    -- real operator, line, direction, day_type or hour_band is ever literally
    -- '*'. If one ever were, two rungs would collide on the same key and break
    -- the primary key the API depends on. Keeping the finest grain wins.
    select *
    from sane
    qualify row_number() over (
        partition by operator, line, direction, day_type, hour_band order by grain_rank
    ) = 1

)

select
    operator,
    line,
    direction,
    day_type,
    hour_band,
    slope_s_per_km,
    intercept_s,
    r2,
    cast(n_obs as bigint)         as n_obs,
    3600.0 / slope_s_per_km       as mean_speed_kmh
from deduped
