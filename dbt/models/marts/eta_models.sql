{#
  The fitted ETA model. One ordinary-least-squares line per grain:

      remaining_secs = intercept_s + slope_s_per_km * remaining_km

  DuckDB has OLS built in as aggregate functions, so the whole "training" step
  is a GROUP BY. No Python, no scikit-learn, no model file to ship, no
  training/serving skew -- the fitted coefficients ARE the mart, and Flask does
  inference with one multiply and one add.

  ---------------------------------------------------------------------------
  The grain, and the fallback chain
  ---------------------------------------------------------------------------
  The finest grain is (operator, line, direction, day_type, hour_band): the 192
  inbound on a Tuesday morning is a genuinely different service from the 192
  inbound on a Sunday night -- different frequency, different traffic,
  different number of stops actually served. operator sits ABOVE all of that,
  because a shared line number is not even the same physical service: '88' is
  a Sheffield cross-city route AND an unrelated Wilmslow-Hale route, and until
  2026-09-12 nothing in this feed told them apart at all.

  But splitting five ways thins every cell, and plenty of combinations have too
  few observations to fit anything trustworthy. The API must never fail to find
  a model, so the same table is emitted at eleven widths, each strictly
  coarser, and Flask walks them in order until one hits:

      (operator, line, direction, day_type, hour_band)   this operator, the real thing
      (operator, line, direction, day_type, '*')         this operator, that day pattern
      (operator, line, direction, '*',      hour_band)   this operator, that time of day
      (operator, line, direction, '*',      '*')         this operator, the route
      (operator, line, '*',       '*',      '*')         this operator, the service number
      ('*',      line, direction, day_type, hour_band)   any operator, the real thing
      ('*',      line, direction, day_type, '*')         any operator, that day pattern
      ('*',      line, direction, '*',      hour_band)   any operator, that time of day
      ('*',      line, direction, '*',      '*')         any operator, the route, both times pooled
      ('*',      line, '*',       '*',      '*')         any operator, the service number
      ('*',      '*',  '*',       '*',      '*')         the network average, always present

  The operator-specific rungs only exist where operator is not null -- every
  ping before 2026-09-12 has no operator at all, so those rows can only ever
  feed the '*'-operator rungs (rungs 6-11, the original six-rung chain this
  table used to be in full). A live bus without an operator, or one whose
  operator has too little history to fit rungs 1-5, falls straight through to
  the same '*' chain that has always existed. Nothing that worked before this
  column existed stopped working.

  Rungs 2/3 (and 7/8) are siblings, not nested: given a thin cell, we would
  rather keep the day pattern and lose the hour, than the reverse -- a Sunday
  fitted from weekday data is worse than a Sunday fitted across the whole day.

  EVERY FALLBACK IS REFITTED from the underlying pings at that width, never
  averaged from the finer rows. Averaging slopes would weight a 300-observation
  grain the same as a 300,000-observation one, which is exactly backwards.

  The eleven fits are generated by the Jinja loop below rather than written out
  eleven times. Each entry lists which columns are real at that grain;
  everything else becomes the literal '*'.

  ---------------------------------------------------------------------------
  Why a grain gets rejected
  ---------------------------------------------------------------------------
  A fit is kept only if it is both well-supported and physically possible:
    - at least 200 observations
    - positive slope (a negative slope says "the further away, the sooner you
      arrive", which is a fit to noise)
    - implied mean speed between 3 and 90 km/h
  A grain that fails is simply not emitted and the lookup falls through to the
  next coarser rung. No model is better than a wrong model.
#}

{%- set key_columns = ['operator', 'line', 'direction', 'day_type', 'hour_band'] -%}
{%- set grains = [
      ['operator', 'line', 'direction', 'day_type', 'hour_band'],
      ['operator', 'line', 'direction', 'day_type'],
      ['operator', 'line', 'direction', 'hour_band'],
      ['operator', 'line', 'direction'],
      ['operator', 'line'],
      ['line', 'direction', 'day_type', 'hour_band'],
      ['line', 'direction', 'day_type'],
      ['line', 'direction', 'hour_band'],
      ['line', 'direction'],
      ['line'],
      []
   ] -%}

with training as (

    select * from {{ ref('int_pings_measured_to_journey_end') }}

),

stacked as (

{% for grain in grains %}
    -- Rung {{ loop.index }}: {% if grain %}grouped by {{ grain | join(', ') }}{% else %}the whole network in one fit{% endif %}

    select
        {% for col in key_columns -%}
        {% if col in grain %}{{ col }}{% else %}'*'{% endif %} as {{ col }},
        {% endfor -%}
        {{ loop.index }} as grain_rank,
        regr_slope(remaining_secs, remaining_km)     as slope_s_per_km,
        regr_intercept(remaining_secs, remaining_km) as intercept_s,
        regr_r2(remaining_secs, remaining_km)        as r2,
        regr_count(remaining_secs, remaining_km)     as n_obs
    from training
    -- A NULL-operator "operator-specific" grain would never be looked up (a
    -- live bus with no operator skips straight to the '*'-operator rungs), so
    -- exclude it rather than waste a rung on a fit nothing will ever match.
    {% if 'operator' in grain %}where operator is not null{% endif %}
    {% if grain %}group by {{ grain | join(', ') }}{% endif %}

{% if not loop.last %}    union all
{% endif %}
{%- endfor %}

),

sane as (

    select *
    from stacked
    where n_obs >= 200                                  -- too thin to trust
      and slope_s_per_km is not null
      and slope_s_per_km > 0                            -- negative pace is a fit to noise
      and 3600.0 / slope_s_per_km between 3 and 90      -- 3 km/h is a parked bus, 90 km/h is not a bus

),

deduped as (

    -- Defensive. The eleven grains are distinct by construction as long as no
    -- real operator, line, direction, day_type or hour_band is ever literally
    -- '*'. If one ever were, two rungs would collide on the same key and break
    -- the primary key the API depends on. Keeping the finest grain wins.
    select *
    from sane
    qualify row_number() over (
        partition by operator, line, direction, day_type, hour_band order by grain_rank
    ) = 1

)

select
    operator,
    line,
    direction,
    day_type,
    hour_band,
    slope_s_per_km,
    intercept_s,
    r2,
    cast(n_obs as bigint)         as n_obs,
    3600.0 / slope_s_per_km       as mean_speed_kmh
from deduped
