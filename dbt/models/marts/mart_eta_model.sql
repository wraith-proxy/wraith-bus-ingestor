{#
  The fitted ETA model. One ordinary-least-squares line per grain:

      remaining_secs = intercept_s + slope_s_per_km * remaining_km

  DuckDB has OLS built in as aggregate functions, so the whole "training" step
  is a GROUP BY. No Python, no scikit-learn, no model file to ship, no
  training/serving skew -- the fitted coefficients ARE the mart, and Flask does
  inference with one multiply and one add.

  ---------------------------------------------------------------------------
  The grain, and the fallback chain
  ---------------------------------------------------------------------------
  The finest grain is (line, direction, day_type, hour_band): the 192 inbound
  on a Tuesday morning is a genuinely different service from the 192 inbound on
  a Sunday night -- different frequency, different traffic, different number of
  stops actually served.

  But splitting three ways thins every cell, and plenty of combinations have too
  few observations to fit anything trustworthy. The API must never fail to find
  a model, so the same table is emitted at six widths, each strictly coarser,
  and Flask walks them in order until one hits:

      (line, direction, day_type, hour_band)   the real thing
      (line, direction, day_type, '*')         that day pattern, all day
      (line, direction, '*',      hour_band)   that time of day, any day
      (line, direction, '*',      '*')         the route, both times pooled
      (line, '*',       '*',      '*')         the service number
      ('*',  '*',       '*',      '*')         the network average, always present

  Note rungs 2 and 3 are siblings, not nested: given a thin cell, we would
  rather keep the day pattern and lose the hour, than the reverse -- a Sunday
  fitted from weekday data is worse than a Sunday fitted across the whole day.

  EVERY FALLBACK IS REFITTED from the underlying pings at that width, never
  averaged from the finer rows. Averaging slopes would weight a 300-observation
  grain the same as a 300,000-observation one, which is exactly backwards.

  The six fits are generated by the Jinja loop below rather than written out six
  times. Each entry lists which columns are real at that grain; everything else
  becomes the literal '*'.

  ---------------------------------------------------------------------------
  Why a grain gets rejected
  ---------------------------------------------------------------------------
  A fit is kept only if it is both well-supported and physically possible:
    - at least 200 observations
    - positive slope (a negative slope says "the further away, the sooner you
      arrive", which is a fit to noise)
    - implied mean speed between 3 and 90 km/h
  A grain that fails is simply not emitted and the lookup falls through to the
  next coarser rung. No model is better than a wrong model.
#}

{%- set key_columns = ['line', 'direction', 'day_type', 'hour_band'] -%}
{%- set grains = [
      ['line', 'direction', 'day_type', 'hour_band'],
      ['line', 'direction', 'day_type'],
      ['line', 'direction', 'hour_band'],
      ['line', 'direction'],
      ['line'],
      []
   ] -%}

with training as (

    select * from {{ ref('int_ping_remaining') }}

),

stacked as (

{% for grain in grains %}
    -- Rung {{ loop.index }}: {% if grain %}grouped by {{ grain | join(', ') }}{% else %}the whole network in one fit{% endif %}

    select
        {% for col in key_columns -%}
        {% if col in grain %}{{ col }}{% else %}'*'{% endif %} as {{ col }},
        {% endfor -%}
        {{ loop.index }} as grain_rank,
        regr_slope(remaining_secs, remaining_km)     as slope_s_per_km,
        regr_intercept(remaining_secs, remaining_km) as intercept_s,
        regr_r2(remaining_secs, remaining_km)        as r2,
        regr_count(remaining_secs, remaining_km)     as n_obs
    from training
    {% if grain %}group by {{ grain | join(', ') }}{% endif %}

{% if not loop.last %}    union all
{% endif %}
{%- endfor %}

),

sane as (

    select *
    from stacked
    where n_obs >= 200                                  -- too thin to trust
      and slope_s_per_km is not null
      and slope_s_per_km > 0                            -- negative pace is a fit to noise
      and 3600.0 / slope_s_per_km between 3 and 90      -- 3 km/h is a parked bus, 90 km/h is not a bus

),

deduped as (

    -- Defensive. The six grains are distinct by construction as long as no
    -- real line, direction, day_type or hour_band is ever literally '*'. If one
    -- ever were, two rungs would collide on the same key and break the primary
    -- key the API depends on. Keeping the finest grain wins.
    select *
    from sane
    qualify row_number() over (
        partition by line, direction, day_type, hour_band order by grain_rank
    ) = 1

)

select
    line,
    direction,
    day_type,
    hour_band,
    slope_s_per_km,
    intercept_s,
    r2,
    cast(n_obs as bigint)         as n_obs,
    3600.0 / slope_s_per_km       as mean_speed_kmh
from deduped
