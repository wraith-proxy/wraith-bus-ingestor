#!/usr/bin/env python3
"""Compile the Ossie metrics in contracts/metrics.ossie.yaml to MetricFlow yaml.

    ops/compile_metrics.py [--ossie FILE] [--out FILE]

Deterministic: sorted keys, no timestamps, no locale or hash-seed dependence.
Only validly aggregable metrics compile: no percentile or median, and any metric over
the eta_models rollup table must filter `operatorRef != '*'`. Marts have no time column,
so no semantic model carries an agg_time_dimension (ticket #52). A composite primary
key becomes one concatenated primary entity (the converter rejects composite keys).
"""

import argparse
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_OSSIE = os.path.join(ROOT, "contracts", "metrics.ossie.yaml")
DEFAULT_OUT = os.path.join(ROOT, "dbt", "semantic", "_semantic.yml")

HEADER = "# GENERATED by ops/compile_metrics.py from contracts/metrics.ossie.yaml. Do not edit.\n"
ROLLUP_SOURCE = "marts.eta_models"
PERCENTILE_RE = re.compile(r"percentile|median|\bp\d{2}|p\d{2}delay", re.I)
EXPR_RE = re.compile(
    r"^\s*(SUM|COUNT|AVG|MIN|MAX)\(\s*(DISTINCT\s+)?(\w+)\.(\w+)\s*\)"
    r"(?:\s+FILTER\s*\(\s*WHERE\s+(\w+)\.(\w+)\s*(!=|<>)\s*'\*'\s*\))?\s*$",
    re.I,
)
AGG = {"SUM": "sum", "COUNT": "count", "AVG": "average", "MIN": "min", "MAX": "max"}


class CompileError(Exception):
    pass


def _parse(metric, datasets):
    name, sql = metric["name"], metric["expression"]["sql"]
    if PERCENTILE_RE.search(name) or PERCENTILE_RE.search(sql):
        raise CompileError(f"{name}: percentile metrics do not aggregate across grains")
    m = EXPR_RE.match(sql)
    if not m:
        raise CompileError(f"{name}: unsupported expression {sql!r}")
    agg, distinct, ds, fld, fds, ffld, _ = m.groups()
    if ds not in datasets or fld not in datasets[ds]["_fields"]:
        raise CompileError(f"{name}: expression names undeclared {ds}.{fld}")
    if not datasets[ds]["source"].startswith("marts."):
        raise CompileError(f"{name}: {ds} is not a mart, MetricFlow can only read marts")
    if datasets[ds]["source"] == ROLLUP_SOURCE:
        if not (fds == ds and ffld == "operatorRef"):
            raise CompileError(
                f"{name}: a metric over {ds} needs the real-operator filter (operatorRef != '*')"
            )
    elif fds:
        if fds != ds or ffld not in datasets[ds]["_fields"]:
            raise CompileError(f"{name}: filter names undeclared {fds}.{ffld}")
    agg_name = "count_distinct" if distinct else AGG[agg.upper()]
    return name, ds, fld, agg_name, ffld if fds else None


def compile_model(model):
    datasets = {
        d["name"]: dict(d, _fields={f["name"]: f for f in d.get("fields", [])})
        for d in model.get("datasets", [])
    }
    parsed = [_parse(m, datasets) for m in model.get("metrics", [])]
    by_ds = {}
    for p in parsed:
        by_ds.setdefault(p[1], []).append(p)
    sems = []
    for ds_name in sorted(by_ds):
        ds = datasets[ds_name]
        table = ds["source"].partition(".")[2]
        col = lambda f: ds["_fields"][f]["expression"]["sql"]  # noqa: E731
        pk = ds.get("primary_key", [])
        expr = " || '|' || ".join(f"cast({col(k)} as varchar)" for k in pk)
        measures = [
            {"name": name, "agg": agg, "expr": col(fld)}
            for name, _, fld, agg, _ in sorted(by_ds[ds_name])
        ]
        dims = [
            {"name": col(f), "type": "categorical", "expr": col(f)}
            for f in sorted(ds["_fields"], key=col)
            if ds["_fields"][f].get("datatype", "String") == "String"
        ]
        sems.append(
            {
                "name": table,
                "description": ds.get("description", ""),
                "model": f"ref('{table}')",
                "entities": [{"name": f"{table}_key", "type": "primary", "expr": expr}],
                "dimensions": dims,
                "measures": measures,
            }
        )
    metrics = []
    for name, ds, fld, agg, ffld in sorted(parsed):
        table = datasets[ds]["source"].partition(".")[2]
        m = {
            "name": name,
            "label": name,
            "type": "simple",
            "description": next(x for x in model["metrics"] if x["name"] == name).get(
                "description", ""
            ),
            "type_params": {"measure": name},
        }
        if ffld:
            col = datasets[ds]["_fields"][ffld]["expression"]["sql"]
            m["filter"] = f"{{{{ Dimension('{table}_key__{col}') }}}} != '*'"
        metrics.append(m)
    doc = {"version": 2, "semantic_models": sems, "metrics": metrics}
    return HEADER + yaml.safe_dump(doc, sort_keys=True, default_flow_style=False, width=100)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ossie", default=DEFAULT_OSSIE)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    with open(args.ossie) as fh:
        model = yaml.safe_load(fh)
    try:
        text = compile_model(model)
    except CompileError as e:
        print(f"compile_metrics: {e}", file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
